// Generate read-only console models from the real PostgreSQL schema.
// Does not modify the database; apply the generated migration with sql:bootstrap.
import {readFile,writeFile} from 'node:fs/promises';
import {cloudAuth,cloudPool,secretValue} from './lib/sql-cloud.mjs';
const root=new URL('../../',import.meta.url);
const migrationArg=process.argv.indexOf('--migration');
const migration=migrationArg<0?'007-complete-console-inspection.sql':process.argv[migrationArg+1];
if(!/^\d{3}-[a-z0-9-]+\.sql$/.test(migration||''))throw new Error('Nombre de migración inválido.');
const diagram=await readFile(new URL('docs/base-de-datos/diagrama-completo.mmd',root),'utf8');
const labels=new Map([...diagram.matchAll(/\s+(\w+)\["([^"]+)"\] \{/g)].map(m=>[m[1],m[2]]));
labels.set('issues','Incidencias de migración');
labels.set('source_documents','Documentos de origen de migración');
const camel=s=>s.replace(/_([a-z])/g,(_,c)=>c.toUpperCase());
const pascal=s=>s.normalize('NFD').replace(/[\u0300-\u036f]/g,'').split(/[^a-zA-Z0-9]+/).filter(Boolean).map(w=>w[0].toUpperCase()+w.slice(1)).join('');
const auth=await cloudAuth();const {pool,close}=await cloudPool(auth,'findi_migration',await secretValue(auth,'FINDI_SQL_MIGRATION_PASSWORD'),1);
try {
 const tables=(await pool.query("SELECT schemaname,tablename FROM pg_tables WHERE schemaname IN ('findi','findi_migration') OR (schemaname='public' AND tablename='findi_schema_migrations') ORDER BY schemaname,tablename")).rows;
 const cols=(await pool.query("SELECT table_schema,table_name,column_name,udt_name FROM information_schema.columns WHERE table_schema IN ('findi','findi_migration','public') ORDER BY ordinal_position")).rows;
 let gql='# Generated by functions/scripts/generate-sql-connect-inspection.mjs.\n# Read-only inspection of existing physical tables; no duplicate tables or CRUD.\n# All connector operations require privileged Admin SDK / console IAM access.\n';
 let sql='-- One read-only view per existing physical table, for privileged console inspection.\nBEGIN;\nCREATE SCHEMA IF NOT EXISTS findi_inspection;\nREVOKE ALL ON SCHEMA findi_inspection FROM PUBLIC;\n';
 let queries='# Generated inspection operations. Browser clients are denied access.\n';
 const manifest=[];
 for(const t of tables){
  const label=labels.get(t.tablename)|| (t.tablename==='findi_schema_migrations'?'Migraciones del esquema SQL':t.tablename);
  const name=pascal(label);const plural='inspeccion'+name;
  const fields=cols.filter(c=>c.table_schema===t.schemaname&&c.table_name===t.tablename);
  const selections=[];const definitions=[];
  for(const c of fields){
   let type='String',expr='"'+c.column_name+'"';
   if(['int2','int4'].includes(c.udt_name))type='Int';
   else if(c.udt_name==='int8')type='Int64';
   else if(c.udt_name==='bool')type='Boolean';
   else if(['float4','float8'].includes(c.udt_name))type='Float';
   else if(['json','jsonb'].includes(c.udt_name))type='Any';
   else if(['timestamp','timestamptz'].includes(c.udt_name))type='Timestamp';
   else if(c.udt_name==='_text')type='[String]';
   else if(!['text','varchar','bpchar'].includes(c.udt_name))expr+='::text';
   selections.push(expr+' AS "'+c.column_name+'"');definitions.push('  '+camel(c.column_name)+': '+type+' @col(name: "'+c.column_name+'")');
  }
  sql+=`CREATE OR REPLACE VIEW findi_inspection.${t.tablename} WITH(security_barrier=true) AS\n SELECT ${selections.join(',')} FROM ${t.schemaname}.${t.tablename};\nREVOKE ALL ON findi_inspection.${t.tablename} FROM PUBLIC;\n`;
  gql+=`\n"""${label}. Tabla física: ${t.schemaname}.${t.tablename}."""\ntype ${name} @view(sql: "SELECT * FROM findi_inspection.${t.tablename}", plural: "${plural}") {\n${definitions.join('\n')}\n}\n`;
  queries+=`\nquery Inspeccionar${name} @auth(level: NO_ACCESS) {\n  ${plural}(limit: 20) { ${fields.map(c=>camel(c.column_name)).join(' ')} }\n}\n`;
  manifest.push({table:t.schemaname+'.'+t.tablename,model:name,query:'Inspeccionar'+name,root:plural,columns:fields.length});
 }
 sql+=`DO $$\nDECLARE reader record;\nBEGIN\n FOR reader IN SELECT rolname FROM pg_roles WHERE rolname IN ('firebasereader_cotizapp-d71c8-database_public','firebasewriter_cotizapp-d71c8-database_public') LOOP\n  EXECUTE format('GRANT USAGE ON SCHEMA findi_inspection TO %I',reader.rolname);\n  EXECUTE format('GRANT SELECT ON ALL TABLES IN SCHEMA findi_inspection TO %I',reader.rolname);\n END LOOP;\nEND $$;\nCOMMIT;\n`;
 const migrationPath=new URL('sql/findi/'+migration,root);
 let previous;try{previous=await readFile(migrationPath,'utf8');}catch(error){if(error.code!=='ENOENT')throw error;}
 if(previous!==undefined&&previous!==sql)throw new Error('No se modifica una migración existente. Usa --migration con un nuevo nombre y revisa el SQL generado.');
 await writeFile(migrationPath,sql);
 await writeFile(new URL('dataconnect/schema/inspection.gql',root),gql);
 await writeFile(new URL('dataconnect/findi-admin/inspection.gql',root),queries);
 await writeFile(new URL('dataconnect/inspection-manifest.json',root),JSON.stringify(manifest,null,2)+'\n');
 console.log(JSON.stringify({physicalTables:tables.length,models:manifest.length,columns:manifest.reduce((n,m)=>n+m.columns,0)}));
 for(const table of ['products','users','stores','product_attributes','quotations'])console.log(table,(await pool.query(`SELECT count(*)::int n FROM findi.${table}`)).rows[0].n);
}finally{await close();}
